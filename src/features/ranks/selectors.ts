// Ranks selectors (ranks.md §1-5; M7 §15, D-424): the rank, the skill minimums still unmet, standing, eligibility and the
// promotion check every rank change goes through. Pure reads of state.
import { archetypeDef } from '../../data/archetypes';
import { WARS, TALENT_ROLL_ORDERS } from '../../data/npcGen.config';
import { KNIGHT_TRIALS, RANK_BY_ID, ranksForPath } from '../../data/rankMinimums';
import { COUNCIL_SEAT, MASTER_APPROVAL, SELECTION, TAKE_PADAWAN_AGE, type TrialId } from '../../data/ranks.config';
import { FORM_IDS, TALENT_DOMAINS } from '../../data/skills';
import { dateFromAbsDay } from '../../engine/calendar';
import { nextFloat, seedRng } from '../../engine/rng';
import type { GameState } from '../../state/gameState';
import { computeCreation, selectCharacter, selectExactAge, selectHumanAge } from '../character/selectors';
import { selectHasFlag, selectFlags } from '../flags/selectors';
import { selectLevelExact } from '../progression/selectors';
import { NO_RECORD, bypassUnmet, knightTrialsDone, percentileOf, standing, trialBlock, unmetMinimums, type TrialRecord } from './rules';

export const selectRank = (s: GameState): string => s.ranks.rank;
export const selectRankName = (s: GameState): string => RANK_BY_ID.get(s.ranks.rank)?.name ?? s.ranks.rank;
export const selectTrialRecord = (s: GameState, t: TrialId): TrialRecord => s.ranks.trials[t] ?? NO_RECORD;

/** The highest lightsaber form level (D-118). */
export const selectHighestForm = (s: GameState): number => Math.max(0, ...FORM_IDS.map((f) => selectLevelExact(s, f)));

/** A minimum key's level: '$highestForm', '$main' (the archetype's main specialty; a form main reads the highest form), or a skill. */
export function selectMinimumLevel(s: GameState, key: string): number {
  if (key === '$highestForm') return selectHighestForm(s);
  if (key === '$main') {
    const main = archetypeDef(selectCharacter(s).archetype).main;
    return main.startsWith('$') ? selectHighestForm(s) : selectLevelExact(s, main);
  }
  return selectLevelExact(s, key);
}

/** The unmet skill minimums of a rank (rankMinimums.ts). */
export const selectUnmetFor = (s: GameState, rankId: string): string[] => unmetMinimums(RANK_BY_ID.get(rankId)?.minimums ?? {}, (k) => selectMinimumLevel(s, k));

/** Years in the current rank (0 when it came with the character and no start day is known: creation counts from the start). */
export function selectYearsInRank(s: GameState): number {
  const since = s.ranks.since ?? s.clock.startDay ?? s.clock.now.day;
  return (s.clock.now.day - since) / 368;
}

/** The character's side for wartime (the start option's faction, else the path's). */
function sideOf(s: GameState): string | null {
  const c = selectCharacter(s);
  return c.start?.faction ?? (c.path === 'jedi' ? 'jediOrder' : c.path === 'sith' ? 'sithEmpire' : null);
}
/** Wartime for the character's side (the WARS table, npcGen.config). */
export function selectWartime(s: GameState): boolean {
  const side = sideOf(s);
  const year = dateFromAbsDay(s.clock.now.day).year;
  return side !== null && WARS.some((w) => w.factions.includes(side) && year >= -w.fromBby && year <= -w.toBby);
}

export const selectHeroic = (s: GameState): boolean => selectFlags(s).some((f) => f.startsWith('heroicAct:'));
export const selectDeedCount = (s: GameState): number => selectFlags(s).filter((f) => f.startsWith('deed:')).length;

/** Relationships with Knights and Masters (or Sith Lords), 0-100: the mean of the positive side of each (ranks.md §1). */
export function selectSeniorRelationships(s: GameState): number {
  const senior = new Set(['jediKnight', 'jediMaster', 'sithLord']);
  const vals = Object.values(s.npcs.byId)
    .filter((n) => senior.has(n.role) && n.status !== 'deceased')
    .map((n) => s.relationships.byNpcId[n.id]?.value ?? 0);
  return vals.length ? Math.max(0, vals.reduce((a, b) => a + b, 0) / vals.length) : 0;
}

// ---- The skill percentile (D-66): the seeded population of NPC Initiates of the same age ----
const POP_CACHE = new Map<string, number[]>();
/**
 * The composite (mean of the highest form, Force Control and Force Sense) of `size` NPC Initiates of age `age` (Human),
 * generated by the closed form: Jedi start ages 2-5, the Force-trained talent distribution. Seeded by the campaign.
 */
export function initiatePopulation(seed: string, age: number, size: number = SELECTION.population): number[] {
  const key = `${seed}:${Math.round(age * 12)}:${size}`;
  const hit = POP_CACHE.get(key);
  if (hit) return hit;
  let rng = seedRng(`initiates:${key}`);
  const out: number[] = [];
  for (let i = 0; i < size; i++) {
    let u: number;
    [u, rng] = nextFloat(rng);
    const start = 2 + 3 * u;
    const talents: Record<string, string> = {};
    for (const d of TALENT_DOMAINS) {
      [u, rng] = nextFloat(rng);
      let x = u;
      for (const [t, w] of TALENT_ROLL_ORDERS.order) {
        if (x < w) {
          if (t !== 'none') talents[d] = t;
          break;
        }
        x -= w;
      }
    }
    const r = computeCreation({ name: 'i', birthDay: 0, startDay: Math.round(age * 368), speciesId: 'human', path: 'jedi', archetype: 'jediGuardian', rank: 'initiate', trainingStartAge: Math.min(start, age - 0.01), talents, dominantHand: 'right', npc: true, ignoreTalentLimit: true } as Parameters<typeof computeCreation>[0]);
    const l = r.levels as Record<string, number>;
    out.push((Math.max(0, ...FORM_IDS.map((f) => l[f] ?? 0)) + (l['forceControl'] ?? 0) + (l['forceSense'] ?? 0)) / 3);
  }
  if (POP_CACHE.size > 64) POP_CACHE.delete(POP_CACHE.keys().next().value!);
  POP_CACHE.set(key, out);
  return out;
}

/** The character's composite and its percentile among Initiates of the same age (D-66). */
export function selectSkillPercentile(s: GameState, size: number = SELECTION.population): number {
  const composite = (selectHighestForm(s) + selectLevelExact(s, 'forceControl') + selectLevelExact(s, 'forceSense')) / 3;
  return percentileOf(composite, initiatePopulation(s.meta.campaignId, selectHumanAge(s), size));
}

/** Standing S, 0-100 (ranks.md §1). */
export function selectStanding(s: GameState, size?: number): number {
  return standing({ percentile: selectSkillPercentile(s, size), deeds: selectDeedCount(s), relationships: selectSeniorRelationships(s) });
}

/** The master's approval conditions (flag-registry §2), the unmet ones. */
export function selectMasterApprovalUnmet(s: GameState): string[] {
  const out: string[] = [];
  if (s.ranks.rank !== 'padawan') out.push('not a Padawan');
  if (selectYearsInRank(s) < KNIGHT_TRIALS.padawanYears) out.push(`under ${KNIGHT_TRIALS.padawanYears} years as a Padawan`);
  if (selectExactAge(s) < 18) out.push('under 18');
  const m = s.ranks.masterId;
  if (!m) out.push('no master recorded');
  else if ((s.relationships.byNpcId[m]?.value ?? 0) < MASTER_APPROVAL.relationship) out.push(`the master's regard under +${MASTER_APPROVAL.relationship}`);
  if (selectUnmetFor(s, 'knight').length) out.push('Knight minimums unmet');
  return out;
}

/** Why a trial cannot be attempted now, or null. */
export function selectTrialBlock(s: GameState, t: TrialId): string | null {
  return trialBlock(
    t,
    {
      rank: s.ranks.rank,
      age: selectExactAge(s),
      padawanYears: s.ranks.rank === 'padawan' ? selectYearsInRank(s) : 0,
      masterApproval: selectHasFlag(s, 'masterApproval'),
      unmetKnight: selectUnmetFor(s, 'knight'),
      unmetInitiate: selectUnmetFor(s, 'padawan'),
      corps: s.ranks.corps !== null,
    },
    selectTrialRecord(s, t),
    s.clock.now.day,
  );
}

/** The Council bypass's unmet conditions (flag-registry §3); empty = it fires. */
export function selectBypassUnmet(s: GameState, size?: number): string[] {
  return bypassUnmet({ wartime: selectWartime(s), heroic: selectHeroic(s), standing: selectStanding(s, size), age: selectExactAge(s), rank: s.ranks.rank, unmetKnight: selectUnmetFor(s, 'knight') });
}

/**
 * Every promotion's requirements (ranks.md §1-2; test 6). Padawan and apprentice come only from being chosen
 * (padawanChosen); Knight: the five trials (wartime credit for Courage and Flesh) or the Council bypass, and the Knight
 * minimums; Master: the minimums and a Padawan trained to Knighthood, or deeds and the Council's decision; Sith Lord: the
 * Lord minimums and a major deed. The rest of the ladder (High Council, Grand Master, Darth) is story only.
 */
export function selectPromotionCheck(s: GameState, to: string): { ok: boolean; reasons: string[] } {
  const c = selectCharacter(s);
  const def = RANK_BY_ID.get(to);
  if (!def) return { ok: false, reasons: [`unknown rank ${to}`] };
  const ladder = ranksForPath(c.path);
  const cur = ladder.find((r) => r.id === s.ranks.rank);
  if (!ladder.some((r) => r.id === to)) return { ok: false, reasons: [`${def.name} is not a rank of the ${c.path} path`] };
  if (!cur || def.order !== cur.order + 1) return { ok: false, reasons: [`${def.name} is not the next rank after ${cur?.name ?? s.ranks.rank}`] };
  const reasons = [...selectUnmetFor(s, to)];
  if (selectExactAge(s) < def.minAge) reasons.push(`age under ${def.minAge}`);
  switch (to) {
    case 'padawan':
    case 'apprentice':
      reasons.push('a Padawan is chosen by a Knight or Master (the selection rolls), never proposed');
      break;
    case 'knight': {
      if (!selectHasFlag(s, 'councilBypassGranted')) {
        const t = knightTrialsDone(s.ranks.trials, selectWartime(s) && selectHeroic(s));
        if (!t.done) reasons.push(`trials not passed: ${t.missing.join(', ')}`);
      }
      break;
    }
    case 'master':
      if (s.ranks.padawansKnighted < 1 && selectDeedCount(s) < 1) reasons.push('no Padawan trained to Knighthood and no deeds for the Council to weigh');
      break;
    case 'lord':
      if (selectDeedCount(s) < 1) reasons.push('a Lord is recognized after a major deed (no deed on record)');
      break;
  }
  return { ok: reasons.length === 0, reasons };
}

/** A Knight may take a Padawan from 25 with the Council's approval (ranks.md §1). */
export const selectMayTakePadawan = (s: GameState): boolean => (s.ranks.rank === 'knight' || s.ranks.rank === 'master') && selectExactAge(s) >= TAKE_PADAWAN_AGE;
/** A High Council seat's skill and standing parts (ranks.md §1; the vacancy is a story event). */
export const selectCouncilSeatUnmet = (s: GameState, size?: number): string[] => [
  ...(s.ranks.rank !== 'master' ? ['not a Master'] : []),
  ...(selectMinimumLevel(s, '$main') < COUNCIL_SEAT.main ? [`main specialty under ${COUNCIL_SEAT.main}`] : []),
  ...(selectStanding(s, size) < COUNCIL_SEAT.standing ? [`standing under ${COUNCIL_SEAT.standing}`] : []),
];
