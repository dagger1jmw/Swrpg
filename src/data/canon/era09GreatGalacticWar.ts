// Era 09 canon roster: the Great Galactic War through the Galactic War, about 3,681-3,630 BBY
// (Docs/SWRPG lore/SW_Characters_09_GreatGalacticWar_ColdWar.md; npc-generation.md §5; D-152, D-155). Complete across
// the whole span: figures who die early (Kao Cen Darach, Darth Vindican) and figures who appear late (the Galactic
// War heroes). `canonId` is the lore index ID (`lore:<slug>`), so the D-81 exact-alias match links a story NPC.
//
// Levels: each sheet is a dated snapshot (mostly the figure's prime). The engine scales the levels to any campaign
// date by the closed-form growth ratio of the entry's archetype between the snapshot age and the current age, so
// Satele Shan as an 18-year-old Padawan at Korriban (3,681) is far below the Grand Master of the sheet. `fixed`
// entries (ancient or immortal beings) do not scale; the justification is in the data.
//
// Mapping: the six core and five Force stats map 1:1. "Shien/Djem So N" sets both forms. Sub-ability proficiency
// ("Telekinesis 88 (Force Push 85%)") sets the sub-ability to base x percent; "Force Body N (Force Speed P%)" sets
// forceSpeed. Abilities not yet in the skill list stay in `unmapped` for the M6 catalog. Non-Force fighters use
// the tier table's "Ranged / Melee" rating as blaster / melee.
//
// Years: `birthSource` / `deathSource` 'lore' are given by the lore files; 'estimate' marks a design default
// (Jared kept the estimates, D-155). Not a person, so not here: the generic war-generation statline.
