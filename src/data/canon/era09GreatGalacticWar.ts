const core = (str: number, agi: number, end: number, wil: number, cha: number, int: number) => ({
  strength: str,
  agility: agi,
  endurance: end,
  willpower: wil,
  charisma: cha,
  intelligence: int,
});
const force = (fs: number, med: number, fk: number, fc: number, fo: number) => ({
  forceSense: fs,
  meditation: med,
  forceKnowledge: fk,
  forceControl: fc,
  forceOutput: fo,
});
