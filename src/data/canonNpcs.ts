// Canon NPCs (npc-generation.md §5; M5). Hand-set entries from Docs/SWRPG lore/SW_Characters_09_GreatGalacticWar_
// ColdWar.md for the 3,661 BBY start. `canonId` is the lore index ID (`lore:<slug>`), so the existing D-81 exact-alias
// match links a story NPC to its entry.
//
// Levels: each sheet is a snapshot (mostly the figure's prime). `levels` are the sheet's numbers at `snapshotBby`;
// at any other date the engine scales them by the closed-form growth ratio of the entry's archetype between the
// snapshot age and the current age (npcGen.ts), so a figure met before their prime is weaker (Satele is a 38-year-old
// Knight in 3,661, not the Grand Master of the sheet) and grows afterwards. `fixed` entries do not scale (ancient or
// immortal beings) and carry the justification npc-generation §5 asks for.
//
// Mapping: the six core and five Force stats map 1:1. "Shien/Djem So N" sets both forms. Sub-ability proficiency
// (e.g. "Telekinesis 88 (Force Push 85%)") sets the sub-ability to base x percent. "Force Body N (Force Speed P%)"
// sets forceSpeed. Abilities not yet in the skill list (Force Drain, Mind Probe, Sith Alchemy, Force Rage, Force
// Body, Force Valor, Battle Foresight) are kept in `unmapped` for the M6 catalog. Non-Force fighters use the tier
// table's "Ranged / Melee" rating as blaster / melee.
//
// Excluded from the 3,661 roster: Kao Cen Darach (killed 3,681 BBY), Revan (in stasis until ~3,640), the eight class
// protagonists, Kira Carsen and Theron Shan (children or not yet active in 3,661), and the generic
// war-generation statline (not a person).
import type { FactionId, NpcRole, SpeciesId } from './entities.config';

export interface CanonNpc {
  canonId: string;
  name: string;
  speciesId: SpeciesId;
  faction: FactionId;
  role: NpcRole;
  archetype: string;
  birthBby: number;
  /** 'lore' when the lore files give the year; otherwise a design default (a question for Jared). */
  birthSource: 'lore' | 'designDefault';
  /** The year the sheet's levels describe (BBY). */
  snapshotBby: number;
  levels: Readonly<Record<string, number>>;
  /** Present = the levels do not scale with age; the justification (npc-generation §5). */
  fixed?: string;
  specialTalents?: readonly string[];
  unmapped?: readonly string[];
  /** Where the figure is in 3,661 BBY when it matters (imprisoned, exiled). */
  note?: string;
}

const core = (str: number, agi: number, end: number, wil: number, cha: number, int: number) => ({
  strength: str,
  agility: agi,
  endurance: end,
  willpower: wil,
  charisma: cha,
  intelligence: int,
});
const force = (fs: number, med: number, fk: number, fc: number, fo: number) => ({
  forceSense: fs,
  meditation: med,
  forceKnowledge: fk,
  forceControl: fc,
  forceOutput: fo,
});
const pct = (base: number, p: number): number => Math.round(base * p);

